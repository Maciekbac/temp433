/* ---- keys ------------------------------------------------------------------- */

__attribute__((noinline))
static void keys(void)
{
    const uint8_t k = A->get_key();
    if (k == APP_KEY_SAVER) {
        g.saver = 1;
        return;
    }
    if (k == APP_KEY_WAKE) {
        g.saver = 0;
        g.prev = APP_KEY_INVALID;
        g.next_draw = 0;
        return;
    }
    if (k == g.prev)
        return;
    g.prev = k;
    if (k == APP_KEY_INVALID)
        return;
    A->backlight_on();
    g.next_draw = 0;
    switch (k) {
    case APP_KEY_EXIT:
        g.running = 0;
        break;
    case APP_KEY_1:
        g.spk ^= 1u;
        A->audio_path(g.spk);
        break;
    case APP_KEY_2:
#ifdef DIAG
        g.r.proto = NO_READING;
#else
        g.n = g.sel = g.top = 0;       /* the table and the counters start over */
#endif
        reset();
        break;
    case APP_KEY_3:
        if (++g.sens >= sizeof THR_DB)
            g.sens = 0;
        reset();
        break;
    case APP_KEY_5:
        if (!g.vhf) {
            g.is_auto ^= 1u;
            retune();
        }
        break;
#ifndef DIAG
    /* raw keys, as the F4HWN list apps: UP / LEFT on the K1 goes up the list */
    case APP_KEY_UP:
        if (g.sel)
            g.sel--;
        if (g.sel < g.top)
            g.top = g.sel;
        break;
    case APP_KEY_DOWN:
        if (g.sel + 1u < g.n)
            g.sel++;
        if (g.sel >= g.top + ROWS_SHOWN)
            g.top = (uint8_t)(g.sel - (ROWS_SHOWN - 1u));
        break;
#endif
    default:
        break;
    }
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api)
{
    uint8_t runs[MAX_RUNS];            /* on the stack, outside the overlay */
    rows_t rows;
    uint16_t floorq[N_PTS];
#ifdef DIAG
    uint8_t keep[FRAME];               /* emptied by retune() -> reset() */
    g.keep = keep;
#else
    sensor_t tab[N_SENS];
    g.tab = tab;
#endif

    A = api;
    g.runs = runs;
    g.rows = &rows;
    g.floorq = floorq;
    g.r.proto = NO_READING;            /* the rest of g starts at 0 */
    g.prev = api->get_key();           /* the MENU that started the app */

    api->af_capture_open();            /* PA4 bias and ADC channel 4, restored by close */
    api->backlight_on();
    g.vfo = api->rx_freq();
    g.vhf = g.vfo < VHF_MAX;
    g.is_auto = g.vfo >= F_FIRST && g.vfo <= F_FIRST + (N_PTS - 1u) * F_STEP;
    g.reg2b = api->bk_read(REG_2B);    /* the loader's retune leaves it in AM */
    api->bk_write(REG_RX_BW, WIDE_BW);
    api->bk_write(REG_2B, (uint16_t)((g.reg2b | 0x0700u) & ~0x0007u));   /* RX filters off */
    api->bk_write(REG_73, (uint16_t)(api->bk_read(REG_73) | 0x0010u));   /* AFC off */
    api->set_agc(false);               /* fixed gain: steady RSSI and pulse levels */
    g.ctrl = (uint16_t)(api->bk_read(REG_CTRL) | CTRL_AF_DAC);
    api->audio_path(false);            /* PA4 is before the speaker amplifier */
    api->set_af(APP_AF_AM);
    retune();
    g.running = 1;

    while (g.running) {
        keys();
        /* the screen before the sweep: a key shows at once, not after a
         * capture (up to 0.9 s) */
        const uint32_t t = api->ticks_ms();
        if (g.led && (int32_t)(t - g.led_until) >= 0) {
            g.led = 0;
            api->led(false);
        }
        if (!g.saver && (int32_t)(t - g.next_draw) >= 0) {
            api->battery_sample();
            draw();
            api->blit_status();
            api->blit_full();
            g.next_draw = t + 500u;
        }
        if (g.vhf)
            api->delay_ms(20);
        else
            scan();
        api->backlight_update();
    }

    /* the loader retunes the VFO (frequency, REG_43, REG_73, REG_30) on return */
    api->af_capture_close();
    api->set_af(APP_AF_MUTE);
    api->audio_path(false);
    api->set_agc(true);                /* its retune keeps a cached AGC state */
    api->bk_write(REG_2B, g.reg2b);
    api->led(false);
}
