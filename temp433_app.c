/* The resident formatters: one local stub each keeps every call a plain bl. */
__attribute__((noinline))
static char *putu(char *o, uint32_t v)
{
    return A->append_u32(o, v);
}

__attribute__((noinline))
static char *puti(char *o, int32_t v)
{
    return A->append_i32(o, v);
}

static char *put(char *o, const char *s)
{
    while (*s)
        *o++ = *s++;
    return o;
}

/* v / scale as "int.frac", scale a power of ten (one digit per zero) */
static char *put_fixed(char *o, uint32_t v, uint32_t scale)
{
    uint64_t qr = __aeabi_uidivmod(v, scale);
    o = putu(o, (uint32_t)qr);
    *o++ = '.';
    uint32_t r = (uint32_t)(qr >> 32);
    while (scale > 1u) {
        scale = (uint32_t)__aeabi_uidivmod(scale, 10u);
        qr = __aeabi_uidivmod(r, scale);
        *o++ = (char)('0' + (uint32_t)qr);
        r = (uint32_t)(qr >> 32);
    }
    return o;
}

/* 10 Hz units -> "434.2125", "433.920" (at least the kHz) */
static char *put_freq(char *o, uint32_t f)
{
    o = put_fixed(o, (uint32_t)__aeabi_uidivmod(f, 10u), 10000u);
    return o[-1] == '0' ? o - 1 : o;
}

static void tiny(char *s, char *end, uint8_t y)
{
    *end = 0;
    A->print_tiny(s, 0, y, false, true);
}

/* ---- radio ------------------------------------------------------------------ */

static uint32_t freq(uint8_t p)
{
    return g.f0 + (uint32_t)p * F_STEP;
}

/* point p of the sweep (VFO: point 0), not retuned when already there: every
 * retune also steps the AF output */
static void go(uint8_t p)
{
    if (p == g.pt)
        return;
    g.pt = p;
    void (*const write)(uint8_t, uint16_t) = A->bk_write;
    const uint32_t f = freq(p);
    write(REG_FREQ_LO, (uint16_t)f);
    write(REG_FREQ_HI, (uint16_t)(f >> 16));
    write(REG_CTRL, 0);                 /* PLL relock and VCO calibration, as the  */
    write(REG_CTRL, g.ctrl);            /* firmware's spectrum sweep does          */
    /* the RSSI reads low for a few ms after this (radio, the same place, VFO
     * -90 dBm; AUTO after 1 / 2 / 4 / 8 ms: -121 / -96 / -89 / -90 dBm), so
     * with measure()'s 1 ms the first reading comes SETTLE_MS after it */
    A->delay_ms(SETTLE_MS - 1u);
}

/* dBm + 160 at the current frequency (REG_67 holds (dBm + 160) x 2) */
static uint8_t measure(void)
{
    A->delay_ms(1);
    A->bk_read(REG_RSSI);               /* the first read may still move */
    return (uint8_t)((A->bk_read(REG_RSSI) & 0x1FFu) >> 1);
}

/* noise floor of point p toward v by 1/2^shift of the difference (truncated
 * toward zero: no drift either way) */
static void learn(uint8_t p, uint8_t v, uint8_t shift)
{
    uint16_t *const q = &g.floorq[p];
    const int32_t d = (int32_t)(v << 8) - *q;
    *q = (uint16_t)(*q + (d >= 0 ? d >> shift : -(-d >> shift)));
}

/* ---- capture ---------------------------------------------------------------- */

/* Sample PA4 until the audio goes quiet.  Each sample is the mean of the last
 * four (200 us: about 6 dB less noise, the 500 us pulses keep their width);
 * the comparator follows the envelope (min and max relax toward each other in
 * ~13 ms) with 1/8 hysteresis and a 2-sample debounce.  Measured in the
 * emulator, Nexus every 5 s with the noise at -128 dBm, decoded of 10 at
 * -121 / -123 dBm: 9 / 1 with no mean and 1/4 hysteresis (the Pogoda433
 * comparator, which missed whole pulses of weak packets on the radio), 10 / 10
 * now.  runs[] gets the length of every level in samples (255 =
 * 12.75 ms or longer), the first (partial) one left out, the last (after the
 * burst) included.  No RSSI read meanwhile: SPI traffic reaches the audio.
 * A new key ends the capture. */
static uint16_t capture(void)
{
    uint8_t *const runs = g.runs;
    uint32_t (*const clk)(void) = A->cycles_48mhz;
    uint16_t (*const sample)(void) = A->af_capture_sample;
    uint32_t next = clk();
    uint16_t lo = 4095u, hi = 0, len = 0, quiet = 0, edges = 0, n = 0, kp = 0, k;
    uint16_t x1 = sample(), x2 = x1, x3 = x1;   /* the mean starts from the first sample */
    uint8_t level = 2, cand = 0;       /* level 2: not known yet */
    g.aborted = 0;
    for (k = 0; k < CAP_MAX; k++) {
        while (app_cycles_before(clk(), next))
            ;
        next += CYC;
        const uint16_t x0 = sample(), x = (uint16_t)((x0 + x1 + x2 + x3) >> 2);
        x3 = x2;
        x2 = x1;
        x1 = x0;
        /* a key pressed now ends the capture (else it would be lost).  The
         * keyboard scan takes 0.15-0.4 ms (3-8 samples, then taken back to
         * back): only inside a level 3 ms long by then (a sync gap, the
         * silence), which it shortens without changing what it means */
        if (len >= KEY_RUN && (uint16_t)(k - kp) >= KEY_EVERY) {
            kp = k;
            const uint8_t key = A->get_key();
            if (key < APP_KEY_INVALID && key != g.prev) {
                g.aborted = 1;
                break;
            }
        }
        hi = x > hi ? x : (uint16_t)(hi - ((hi - x) >> 8));
        lo = x < lo ? x : (uint16_t)(lo + ((x - lo) >> 8));
        len++;
        if (++quiet > (edges < PACKET_RUNS ? QUIET_EMPTY : QUIET))
            break;
        const uint16_t span = (uint16_t)(hi - lo), mid = (uint16_t)((hi + lo) >> 1), h = span >> 3;
        if (span < MIN_SPAN)
            continue;
        const uint8_t bit = level == 1u ? x + h > mid : x > mid + (level ? 0u : h);
        if (bit == level) {
            cand = 0;
            continue;
        }
        if (++cand < DEB)
            continue;
        if (level < 2u) {               /* the run before the first edge is partial */
            const uint16_t r = (uint16_t)(len - DEB);
            runs[n++] = (uint8_t)(r > 255u ? 255u : r);
            if (r >= MIN_EDGE) {
                quiet = 0;
                edges++;
            }
            if (n >= MAX_RUNS - 1u)
                break;
        }
        level = bit;
        len = DEB;
        cand = 0;
    }
    if (level < 2u)
        runs[n++] = (uint8_t)(len > 255u ? 255u : len);   /* the silence after the burst */
    g.cap = k;

    /* the carrier off is the parity with the longer total (PPM pulses take
     * about a quarter of the time), the first and the last run left out: the
     * level after the burst is unreliable (the AC-coupled detector drifts,
     * noise).  Not the longest run: on the radio the comparator once settled
     * on the first one (108 20 60 39, then 10 / 20 / 40 / 80), and noise once
     * stretched a pulse to 99 samples, past the 80-sample sync gap */
    int32_t d = 0;                      /* runs[n-2] - runs[n-3] + ... +- runs[1] */
    for (uint16_t i = 1; i + 1u < n; i++)
        d = (int32_t)runs[i] - d;
    g.off = (uint8_t)((d <= 0) ^ (n & 1u));   /* n odd: d is odd minus even */
    return n;
}

/* ---- demodulation ----------------------------------------------------------- */

/* a row as long as MIN_ROW makes the capture a packet, decoded or not */
static void row_end(void)
{
    rows_t *const r = g.rows;
    const uint8_t b = r->bits[g.nrows];
    if (b >= MIN_ROW)
        g.pkt = PACKET;
    if (b && g.nrows < ROWS - 1u)
        g.nrows++;
}

/* PPM: the gap after a pulse is the bit, a long gap ends the row */
static void emit(const fam_t *f, uint16_t gap)
{
    rows_t *const r = g.rows;
    if (gap > f->row_gap) {
        row_end();
        return;
    }
    const uint8_t n = r->bits[g.nrows];
    if (n < ROW_BYTES * 8u) {
        if (gap > f->thr)
            r->bytes[g.nrows][n >> 3] |= (uint8_t)(0x80u >> (n & 7u));
        r->bits[g.nrows] = (uint8_t)(n + 1u);
    }
}

/* runs -> rows for one family; a pulse shorter than the glitch length is merged
 * into the gap around it, a gap that short into the pulses around it.  A
 * pulse longer than pmax is the real one plus noise that switched the
 * comparator on early, so the excess goes back to the gap before it (weak
 * packets otherwise turn a 1 bit into a 0). */
static void demod(const fam_t *f, uint16_t n)
{
    const uint8_t *const runs = g.runs;
    memset(g.rows, 0, sizeof(rows_t));
    g.nrows = 0;
    uint16_t pulse = 0, gap = 0;
    for (uint16_t i = (uint16_t)(g.off ? 0u : 1u); i < n; i = (uint16_t)(i + 2u)) {
        uint16_t p = runs[i];
        const uint16_t q = i + 1u < n ? runs[i + 1u] : 255u;
        if (p > f->pmax) {
            gap = (uint16_t)(gap + p - f->pulse);
            p = f->pulse;
        }
        if (pulse && p < f->glitch) {   /* noise inside a gap        */
            gap = (uint16_t)(gap + p + q);
            continue;
        }
        if (pulse && gap < f->glitch) { /* a dropout inside a pulse  */
            pulse = (uint16_t)(pulse + gap + p);
            gap = q;
            continue;
        }
        if (pulse)
            emit(f, gap);
        pulse = p;
        gap = q;
    }
    if (pulse)
        emit(f, gap);
    row_end();
}

/* ---- protocol matching ------------------------------------------------------ */

/* len (<= 16) bits of the current row from data bit pos (after the skipped bits) */
static uint16_t bits(uint8_t pos, uint8_t len)
{
    uint16_t v = 0;
    pos = (uint8_t)(pos + g.skip);
    while (len--) {
        v = (uint16_t)((v << 1) | ((g.row[pos >> 3] >> (7u - (pos & 7u))) & 1u));
        pos++;
    }
    return v;
}

static uint8_t crc8(uint8_t rem, uint8_t b, uint8_t poly)
{
    rem ^= b;
    for (uint8_t i = 0; i < 8u; i++)
        rem = (uint8_t)(rem & 0x80u ? (rem << 1) ^ poly : rem << 1);
    return rem;
}

/* noinline here and on decode(), grab(), put_t10(), rput(), draw() and keys():
 * GCC 13.3 -Os makes the whole smaller with them out of line (each measured
 * on both builds; inlined into app_main they cost ~150 B more in all) */
__attribute__((noinline))
static bool check(const proto_t *p)
{
    const uint8_t c1 = p->c1;
    switch (p->check) {
    case C_NIBSUM: {                    /* sum of the nibbles of c1 bits, c2 bits of it */
        uint16_t sum = 0;
        for (uint8_t pos = 0; pos < c1; pos = (uint8_t)(pos + 4u)) {
            const uint8_t rest = (uint8_t)(c1 - pos), len = rest < 4u ? rest : 4u;
            sum = (uint16_t)(sum + (bits(pos, len) << (4u - len)));
        }
        return (sum & ((1u << p->c2) - 1u)) == bits(c1, p->c2);
    }
    case C_CRC8: {                      /* CRC-8 of c1 bits (zero padded) = the next byte */
        uint8_t x = p->c3;
        for (uint8_t pos = 0; pos < c1; pos = (uint8_t)(pos + 8u)) {
            const uint8_t rest = (uint8_t)(c1 - pos), len = rest < 8u ? rest : 8u;
            x = crc8(x, (uint8_t)(bits(pos, len) << (8u - len)), p->c2);
        }
        return x == bits(c1, 8);
    }
    default:                            /* C_NONE: the repeats decide */
        return true;
    }
}

/* T_S12 only so far: 12-bit two's complement, 0.1 C */
static int16_t temperature(const proto_t *p)
{
    int16_t t = (int16_t)bits(p->t_pos, 12);
    return (int16_t)(t & 0x800 ? t - 4096 : t);
}

/* h_len bits (0: none), 1-100 % */
static uint8_t humidity(const proto_t *p)
{
    if (!p->h_len)
        return NO_HUM;
    const uint8_t h = (uint8_t)bits(p->h_pos, p->h_len);
    return h && h <= 100u ? h : NO_HUM;
}

/* identical rows to row r (itself included) */
static uint8_t same(uint8_t r)
{
    const rows_t *const rs = g.rows;
    uint8_t n = 0;
    for (uint8_t k = 0; k < g.nrows; k++) {
        if (rs->bits[k] != rs->bits[r])
            continue;
        uint8_t i = 0;
        while (i < ROW_BYTES && rs->bytes[k][i] == rs->bytes[r][i])
            i++;
        n = (uint8_t)(n + (i == ROW_BYTES));
    }
    return n;
}

/* try the protocols of family f on its rows; true when one decoded */
static bool match(uint8_t f)
{
    proto_t p;
    for (uint8_t i = 0; i < PROTO_COUNT; i++) {
        asset((uint16_t)(PROTOS + i * PROTO_SIZE), &p, PROTO_SIZE);
        if (p.fam != f)
            continue;
        for (uint8_t r = 0; r < g.nrows; r++) {
            const uint8_t n = g.rows->bits[r];
            if (n < p.bmin || n > p.bmax)
                continue;
            g.row = g.rows->bytes[r];
            g.skip = p.skip;
            if (p.fix_len && bits(p.fix_pos, p.fix_len) != (uint16_t)(p.fix_hi << 8 | p.fix_lo))
                continue;
            if (!check(&p) || same(r) < p.reps)
                continue;
            const int16_t t = temperature(&p);
            if (t < -400 || t > 700)
                continue;
            g.r.proto = i;
            g.r.id = (uint8_t)bits(p.id_pos, p.id_len);
            g.r.ch = (uint8_t)(p.ch_len ? bits(p.ch_pos, p.ch_len) + (p.flags & F_CH1) : 0u);
            g.r.t10 = t;
            g.r.hum = humidity(&p);
            g.r.low = (uint8_t)(bits(p.bat, 1) ^ ((p.flags & F_BATOK) ? 1u : 0u));
            return true;
        }
    }
    return false;
}

__attribute__((noinline))
static uint8_t decode(uint16_t n)
{
    fam_t f;
    g.pkt = EMPTY;
    for (uint8_t i = 0; i < FAM_COUNT; i++) {
        asset((uint16_t)(FAMS + i * FAM_SIZE), &f, FAM_SIZE);
        demod(&f, n);
        if (match(i))
            return DECODED;
    }
    return g.pkt;
}

#ifdef DIAG
/* DIAG: every capture to the USB serial port: a 12-byte header 'T' '4', seq,
 * result, level and noise floor (dBm + 160), protocol (0xFF: none),
 * carrier-off parity, runs (u16 LE), samples (u16 LE), then the runs; in
 * 64-byte writes, as the F4HWN KISS TNC app sends.  The USB cable brings the
 * PC's noise into the receiver (-80 dBm measured), so weak packets are heard
 * without it: the first packet no protocol took since the counters were
 * cleared waits in RAM and follows the first capture a host reads.  Not the
 * last one: plugging the cable in brings a burst of noise packets.  Only one
 * (the stack keeps ~1.4 KB free); keep[0] is 'T' while it waits. */
#define FRAME       (12u + MAX_RUNS)

/* false when no host took them */
static bool send(const uint8_t *h, const uint8_t *runs, uint16_t n)
{
    bool (*const write)(uint8_t, const void *, uint16_t) = A->serial_write;
    if (!write(APP_SERIAL_USB, h, 12u))
        return false;
    for (uint16_t i = 0; i < n; i = (uint16_t)(i + 64u)) {
        const uint16_t left = (uint16_t)(n - i);
        if (!write(APP_SERIAL_USB, runs + i, left < 64u ? left : 64u))
            return false;
    }
    return true;
}

static void dump(uint8_t res, uint8_t level, uint8_t pt, uint16_t n)
{
    const uint8_t h[12] = { 'T', '4', g.seq++, res, level, (uint8_t)((g.floorq[pt] + 128u) >> 8),
                            res == DECODED ? g.r.proto : 0xFFu, g.off,
                            (uint8_t)n, (uint8_t)(n >> 8), (uint8_t)g.cap, (uint8_t)(g.cap >> 8) };
    if (send(h, g.runs, n)) {
        uint8_t *const f = g.keep;
        if (f[0] && send(f, f + 12, (uint16_t)(f[8] | f[9] << 8)))
            f[0] = 0;
        return;
    }
    if (res != PACKET || g.keep[0])
        return;
    uint8_t *const f = g.keep;
    for (uint16_t i = 0; i < 12u + n; i++)
        f[i] = i < 12u ? h[i] : g.runs[i - 12u];
}
#endif

/* ---- search ----------------------------------------------------------------- */

#ifndef DIAG
/* the reading in g.r into the table: the same sensor (protocol, ID, channel)
 * is updated in place, a new one goes at the end (the order they were first
 * heard in); a full table first drops the sensor heard longest ago */
static void store(void)
{
    sensor_t *const t = g.tab;
    uint8_t i = 0, old = 0;
    for (; i < g.n; i++) {
        if (t[i].proto == g.r.proto && t[i].id == g.r.id && t[i].ch == g.r.ch)
            break;
        if ((int32_t)(t[i].seen - t[old].seen) < 0)
            old = i;
    }
    uint16_t count = 1;
    if (i < g.n) {
        count = (uint16_t)(t[i].count + 1u);
    } else if (i == N_SENS) {
        for (i = old; i + 1u < N_SENS; i++)
            t[i] = t[i + 1u];
    } else {
        g.n++;
    }
    t[i] = g.r;
    t[i].count = count;
}
#endif

/* point p (level v) went over the threshold */
__attribute__((noinline))
static void grab(uint8_t p, uint8_t v)
{
    uint8_t best = p, bv = v;
    if (g.is_auto) {                    /* the wide filter also sees the next points */
        for (uint8_t k = (uint8_t)(p - 1u); k != (uint8_t)(p + 3u); k = (uint8_t)(k + 2u)) {
            if (k >= N_PTS)
                continue;
            go(k);
            const uint8_t w = measure();
            if (w > bv) {
                best = k;
                bv = w;
            }
        }
        go(best);
    }
    g.stops++;
    const uint16_t n = capture();
    const uint8_t res = decode(n);
#ifdef DIAG
    dump(res, bv, best, n);
#endif
    const uint32_t now = A->ticks_ms();
    if (res == EMPTY && !g.aborted) {   /* a steady carrier joins the noise */
        g.empties++;
        g.empty_smp += g.cap;
        learn(p, v, 1);
        if (best != p)
            learn(best, bv, 1);
    } else {
        g.packets++;
        g.hold_pt = best;
        g.hold_until = now + HOLD_MS;
    }
    if (res == DECODED) {
        g.ok++;
        g.r.f = freq(best);
        g.r.rssi = bv;
        g.r.seen = now;
#ifndef DIAG
        store();
#endif
        A->backlight_on();
        A->led(true);
        g.led = 1;
        g.led_until = now + 150u;
    }
    g.next_draw = 0;
}

/* one AUTO sweep, or VFO_VISITS readings of the VFO frequency */
static void scan(void)
{
    const uint32_t now = A->ticks_ms();
    const bool armed = (int32_t)(now - g.armed) >= 0;
    const bool hold = (int32_t)(now - g.hold_until) < 0;
    const uint32_t thr = (uint32_t)THR_DB[g.sens] << 8;
    const uint8_t visits = g.is_auto ? SWEEP : VFO_VISITS;
    for (uint8_t k = 0; k < visits; k++) {
        /* an AUTO sweep takes ~0.2 s (SETTLE_MS a point): a key pressed
         * meanwhile ends it, as one ends a capture (else it could be lost) */
        if ((k & 7u) == 7u) {
            const uint8_t key = A->get_key();
            if (key < APP_KEY_INVALID && key != g.prev)
                return;
        }
        uint8_t p = 0, hot = 1;
        if (g.is_auto) {
            p = CENTER;
            if (k & 1u) {
                p = (uint8_t)(k >> 1);
                p = (uint8_t)(p + (p >= CENTER));
                hot = 0;
            }
        }
        go(p);
        const uint8_t v = measure();
        uint16_t *const q = &g.floorq[p];
        if (!*q) {                      /* the first reading as it is */
            *q = (uint16_t)(v << 8);
            continue;
        }
        if ((uint32_t)(v << 8) >= *q + thr) {
            if (armed && !(hold && (uint8_t)(p - g.hold_pt + 1u) <= 2u)) {
                grab(p, v);
                return;
            }
            continue;                   /* a signal: not the noise */
        }
        learn(p, v, hot ? 6u : 3u);     /* AUTO: ~0.5 s for the frequent point, ~1.6 s for the others */
    }
}

/* the counters start over with what is measured */
static void reset(void)
{
    g.stops = g.empties = g.packets = g.ok = 0;
    g.empty_smp = 0;
    g.t0 = A->ticks_ms();
#ifdef DIAG
    g.keep[0] = 0;                     /* the next unrecognised packet is kept */
#endif
}

/* mode or frequency changed: the noise floor is learned again */
static void retune(void)
{
#ifdef DIAG
    g.f0 = g.is_auto ? g.vfo - CENTER * F_STEP : g.vfo;
#else
    g.f0 = g.is_auto ? F_FIRST : g.vfo;
#endif
    memset(g.floorq, 0, N_PTS * sizeof(uint16_t));
    g.pt = NO_PT;
    reset();
    g.armed = g.t0 + LEARN_MS;
    g.hold_until = g.t0;
}

/* ---- screen ----------------------------------------------------------------- */

/* "433.80-434.04" (AUTO) or the VFO frequency */
static char *put_range(char *o)
{
    if (!g.is_auto)
        return put_freq(o, g.f0);
    o = put_fixed(o, (uint32_t)__aeabi_uidivmod(g.f0, 1000u), 100u);
    *o++ = '-';
    return put_fixed(o, (uint32_t)__aeabi_uidivmod(freq(N_PTS - 1u), 1000u), 100u);
}

/* " ok 48 ?3": decoded packets, packets no protocol took */
static char *put_counts(char *o, const char *s)
{
    o = put(putu(put(o, s + T_OK), g.ok), s + T_UNKNOWN);
    return putu(o, (uint32_t)(g.packets - g.ok));
}

/* 0.1 C as "-12.3" */
__attribute__((noinline))
static char *put_t10(char *o, int16_t t)
{
    if (t < 0) {
        *o++ = '-';
        t = (int16_t)-t;
    }
    return put_fixed(o, (uint32_t)t, 10u);
}

